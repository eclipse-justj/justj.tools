package org.eclipse.justj.codegen.model.util;


import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import org.eclipse.emf.common.util.URI;
import org.eclipse.emf.ecore.resource.URIConverter;


public class TemurinIndexer
{
  private static final Pattern ASSETS_PATTERN = Pattern.compile("\"link\": \"([^\"]+\\.(zip|tar.gz))\"");

  private static final Pattern VERSION_PATTERN = Pattern.compile("jdk-([0-9.+]+)/");

  private static final Pattern BETA_VERSION_PATTERN = Pattern.compile("jdk-([0-9.+]+)-ea-beta/");

  private static final String BEGIN_MARKER = "// Begin generated by /org.eclipse.justj.codegen/src/org/eclipse/justj/codegen/model/util/TemurinIndexer.java";

  private static final String END_MARKER = "// End generated by /org.eclipse.justj.codegen/src/org/eclipse/justj/codegen/model/util/TemurinIndexer.java";

  private static final String BEGIN_BETA_MARKER = "// Begin beta generated by /org.eclipse.justj.codegen/src/org/eclipse/justj/codegen/model/util/TemurinIndexer.java";

  private static final String END_BETA_MARKER = "// End beta generated by /org.eclipse.justj.codegen/src/org/eclipse/justj/codegen/model/util/TemurinIndexer.java";

  private static Path cache;

  public static void main(String[] argsx) throws Exception
  {
    var arguments = new ArrayList<String>(List.of(argsx));
    if (arguments.size() > 1)
    {
      cache = Path.of(arguments.remove(0));
    }

    generate(false, arguments);
    generate(true, arguments);
  }

  public static void generate(boolean beta, List<String> arguments) throws Exception
  {
    var byteArrayOutputStream = new ByteArrayOutputStream()
      {
        int start = 0;

        @Override
        public void flush() throws java.io.IOException
        {
          super.flush();
          System.out.write(buf, start, count - start);
          start = count;
        }
      };

    var out = new PrintStream(byteArrayOutputStream, true, StandardCharsets.UTF_8);

    out.println(beta ? BEGIN_BETA_MARKER : BEGIN_MARKER);

    for (var repo : beta ? new String []{ "28" } : new String []{ "11", "17", "21", "25", "27" })
    {
      var releasesURI = beta
        ? URI.createURI("https://api.adoptium.net/v3/assets/feature_releases/" + repo + "/ea?image_type=jdk&jvm_impl=hotspot&project=jdk&vendor=eclipse")
        : URI.createURI("https://api.adoptium.net/v3/assets/latest/" + repo + "/hotspot?image_type=jdk&vendor=eclipse");
      var content = getContent(releasesURI);

      var perVersionDownloadURLs = new TreeMap<Version, List<String>>(Comparator.reverseOrder());
      var jdkDownloadURLs = new ArrayList<String>();
      for (var assetsMatcher = ASSETS_PATTERN.matcher(content); assetsMatcher.find();)
      {
        var url = assetsMatcher.group(1).replace("%2B", "+");
        var versionMatcher = (beta ? BETA_VERSION_PATTERN : VERSION_PATTERN).matcher(url);
        versionMatcher.find();
        var version = Version.of(versionMatcher.group(1));
        perVersionDownloadURLs.computeIfAbsent(version, it -> new ArrayList<>()).add(url);

        jdkDownloadURLs.add(url);
      }

      out.println();

      var entry = perVersionDownloadURLs.entrySet().iterator().next();
      var version = entry.getKey();

      var windowsAarch64Type = "aarch64_windows";
      var jdkURL = getURL(perVersionDownloadURLs, windowsAarch64Type);
      if (jdkURL == null && version.compareTo(new Version(12, 0, 0, 0, 0, 0, "")) > 0)
      {
        // https://www.microsoft.com/openjdk
        // https://gitlab.eclipse.org/eclipsefdn/emo-team/iplab/-/work_items/29542
        // https://learn.microsoft.com/en-us/java/openjdk/download
        //
        var downloadContent = getContent(URI.createURI("https://learn.microsoft.com/en-us/java/openjdk/download"));
        var olderDownloadContent = getContent(URI.createURI("https://learn.microsoft.com/en-us/java/openjdk/older-releases"));

        var microsoftJDKURLPattern = Pattern.compile("href=\"(https://[^\"]+microsoft-jdk-" + version.toString().replaceAll("\\+.*", "") + "-windows-aarch64.zip)\"");
        var matcher = microsoftJDKURLPattern.matcher(downloadContent + olderDownloadContent);
        if (matcher.find())
        {
          jdkURL = matcher.group(1);
          perVersionDownloadURLs.get(version).add(jdkURL);
          windowsAarch64Type = "-windows-aarch64";
        }
      }

      out.println("def java" + repo + "Adoptium = [");
      out.println("  label: 'Java " + repo + " (Adoptium)" + (beta ? " Early Access Beta" : "") + "',");
      out.println("  BUILD_DESCRIPTION: 'Adoptium Java " + version + "',");
      out.println("  PUBLISH_LOCATION_PREFIX: \"${defaultPrefix}\",");
      out.println("  JUSTJ_MANIFEST_URL: \"${justjURL}/${defaultPrefix}/" + repo + "/downloads/latest/justj.manifest\",");

      printEntry(out, "JDK_URLS_WINDOWS", "x64_windows", perVersionDownloadURLs);
      printEntry(out, "JDK_URLS_WINDOWS_AARCH64", windowsAarch64Type, perVersionDownloadURLs);

      printEntry(out, "JDK_URLS_MACOS", "x64_mac", perVersionDownloadURLs);
      printEntry(out, "JDK_URLS_MACOS_AARCH64", "aarch64_mac", perVersionDownloadURLs);

      printEntry(out, "JDK_URLS_LINUX", "x64_linux", perVersionDownloadURLs);
      printEntry(out, "JDK_URLS_LINUX_AARCH64", "aarch64_linux", perVersionDownloadURLs);
      printEntry(out, "JDK_URLS_LINUX_PPC64LE", "ppc64le_linux", perVersionDownloadURLs);
      printEntry(out, "JDK_URLS_LINUX_RISCV64", "riscv64_linux", perVersionDownloadURLs);

      out.println("  BUILD_TYPE: 'nightly',");
      out.println("  PROMOTE: 'true'");
      out.println("]");
    }

    out.println();
    out.println(beta ? END_BETA_MARKER : END_MARKER);

    if (arguments.size() > 0)
    {
      var target = Paths.get(arguments.get(0));
      var contents = Files.readString(target);
      var newGeneratedContents = new String(byteArrayOutputStream.toByteArray(), StandardCharsets.UTF_8);
      if (!contents.contains("\r\n") && newGeneratedContents.contains("\r\n"))
      {
        newGeneratedContents = newGeneratedContents.replace("\r\n", "\n");
      }
      contents = contents.replaceAll(
        "(?s)" + Pattern.quote(beta ? BEGIN_BETA_MARKER : BEGIN_MARKER) + ".*?" + Pattern.quote(beta ? END_BETA_MARKER : END_MARKER) + "\r?\n",
        Matcher.quoteReplacement(newGeneratedContents));
      Files.writeString(target, contents);
    }
  }

  private static void printEntry(PrintStream out, String name, String type, Map<Version, List<String>> perVersionDownloadURLs)
  {
    var jdkURL = getURL(perVersionDownloadURLs, type);
    if (jdkURL != null && !perVersionDownloadURLs.values().iterator().next().contains(jdkURL))
    {
      out.println("  " + name + ": '''");
      out.println("    ''', // " + jdkURL);
    }
    else
    {
      out.println("  " + name + ": '''");
      if (jdkURL != null)
      {
        out.println("    " + jdkURL);
      }
      out.println("    ''',");
    }
  }

  private static String getURL(Map<Version, List<String>> perVersionDownloadURLs, String type)
  {
    for (var downloadURLs : perVersionDownloadURLs.values())
    {
      for (var downloadURL : downloadURLs)
      {
        if (downloadURL.contains(type))
        {
          return downloadURL;
        }
      }
    }

    return null;
  }

  private static Path getCachePath(URI uri)
  {
    if (cache == null)
    {
      return null;
    }

    var decodedURI = URI.decode(uri.toString());
    var uriSegments = decodedURI.split("[:/?#&;]+");
    var result = cache.resolve(String.join("/", uriSegments));
    if (uri.hasTrailingPathSeparator())
    {
      return result.resolve("-folder-contents");
    }
    return result;
  }

  private static String getContent(URI uri) throws IOException
  {
    var path = getCachePath(uri);
    if (path != null && Files.isRegularFile(path))
    {
      return Files.readString(path);
    }

    try (var in = URIConverter.INSTANCE.createInputStream(uri))
    {
      var content = new String(in.readAllBytes(), StandardCharsets.UTF_8);
      if (path != null)
      {
        Files.createDirectories(path.getParent());
        Files.writeString(path, content);
      }
      return content;
    }
  }

  private static record Version(int major, int minor, int micro, int patch, int extra, int offset, String suffix) implements Comparable<Version>
  {
    private static final Pattern PARTS = Pattern.compile(
      "(?<major>\\d+)([.](?<minor>\\d+)([.](?<micro>\\d+)([.](?<patch>\\d+)([.](?<extra>\\d+))?)?)?)?[+](?<offset>\\d+)(?<suffix>.*)");

    public static Version of(String version)
    {
      var matcher = PARTS.matcher(version);
      if (!matcher.matches())
      {
        throw new IllegalArgumentException(version);
      }

      var major = Integer.parseInt(matcher.group("major"));
      var minor = matcher.group("minor") == null ? 0 : Integer.parseInt(matcher.group("minor"));
      var micro = matcher.group("micro") == null ? 0 : Integer.parseInt(matcher.group("micro"));
      var patch = matcher.group("patch") == null ? 0 : Integer.parseInt(matcher.group("patch"));
      var extra = matcher.group("extra") == null ? 0 : Integer.parseInt(matcher.group("extra"));
      var offset = Integer.parseInt(matcher.group("offset"));
      var suffix = matcher.group("suffix");
      return new Version(major, minor, micro, patch, extra, offset, suffix);
    }

    @Override
    public int compareTo(Version version)
    {
      var compare = Integer.compare(major, version.major);
      if (compare == 0)
      {
        compare = Integer.compare(minor, version.minor);
        if (compare == 0)
        {
          compare = Integer.compare(micro, version.micro);
          if (compare == 0)
          {
            compare = Integer.compare(patch, version.patch);
            if (compare == 0)
            {
              compare = Integer.compare(extra, version.extra);
              if (compare == 0)
              {
                compare = Integer.compare(offset, version.offset);
              }
            }
          }
        }
      }
      return compare;
    }

    @Override
    public final String toString()
    {
      return major + //
        (minor == 0 && micro == 0 && patch == 0 && extra == 0 ? "" : "." + //
          (minor + (micro == 0 && patch == 0 && extra == 0 ? "" : "." + //
            (micro + (patch == 0 && extra == 0 ? "" : "." + //
              (patch + (extra == 0 ? "" : "." + extra)))))))
        + "+" + offset + suffix;
    }
  }
}
